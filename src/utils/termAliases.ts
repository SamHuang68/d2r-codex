/** 原查詢，加上把舊寫法換成遊戲寫法的查詢（沒有舊寫法時只有原查詢） */
export function expandLegacyQuery(query: string): string[] {
  let alt = query;
  // 舊譯名是完整名稱，先換；站內舊寫法多半是名稱裡的一小段（例：十字弓→弩），後換，才不會把舊譯名改得面目全非
  for (const [oldTerm, gameTerm] of OLD_TRANSLATION_ALIASES) if (alt.includes(oldTerm)) alt = alt.split(oldTerm).join(gameTerm);
  for (const [oldTerm, gameTerm] of LEGACY_TERM_ALIASES) if (alt.includes(oldTerm)) alt = alt.split(oldTerm).join(gameTerm);
  return alt === query ? [query] : [query, alt];
}
