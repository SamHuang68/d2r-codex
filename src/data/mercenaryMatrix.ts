export type MercTierKey = 'start' | 'mf' | 'bis';

export interface MercGearItemRef {
  name: string;        // 官方中文名 (例如 "靈光")
  nameEn: string;      // 英文名 (例如 "Insight")
  nameClassic?: string;// 舊版俗稱 (例如 "眼光")
  baseName?: string;   // 推薦底材 (例如 "無形 斬鐮")
  baseNameEn?: string; // 推薦底材英文 (例如 "Thresher")
  note?: string;       // 核心價值說明 (例如 "17級冥想靈氣，無限回魔")
  ethereal?: boolean;  // 是否推薦無形
}

export interface MercTierBuild {
  tier: MercTierKey;
  label: string;         // "全裝成形" | "打寶專精" | "頂規畢業"
  summary: string;       // 一句話戰術核心
  mercAct: number;       // 1, 2, 3, 5
  mercTypeZh: string;    // 例如 "第二章 · 祈禱型 (普通/地獄)"
  hirelingId: number;    // hireling.json 基礎 id
  weapon: MercGearItemRef;
  weapon2?: MercGearItemRef; // 第五章雙持專用
  helm: MercGearItemRef;
  armor: MercGearItemRef;
  keyAuras: string[];    // 賦予的核心光環列表
  synergyNote: string;   // 與主人流派的化學反應
}

export interface ClassMercMatrixEntry {
  id: string;
  classZh: string;
  classEn: string;
  classCode: 'ama' | 'sor' | 'nec' | 'pal' | 'bar' | 'dru' | 'ass' | 'war';
  buildName: string;
  role: string;
  coreProblem: string;   // 該流派痛點（需要傭兵補足什麼）
  bestMercSummary: string;
  tiers: {
    start: MercTierBuild;
    mf: MercTierBuild;
    bis: MercTierBuild;
  };
}

